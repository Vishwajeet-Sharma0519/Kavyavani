import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { normalizeSearch } from "../src/data/search.ts";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const raw = await readFile(
  path.join(root, "../kavya_merged_final.json"),
  "utf8",
);
const source = JSON.parse(raw);
if (!Array.isArray(source)) throw new Error("Dataset must be an array.");
const hash = (value) =>
  createHash("sha256").update(value).digest("hex").slice(0, 16);
const norm = (value) =>
  value.normalize("NFKC").toLocaleLowerCase().replace(/\s+/g, " ").trim();
const fingerprint = hash("search-schema-2\n" + raw);
const dir = path.join(root, "public/data", fingerprint);
await mkdir(dir, { recursive: true });
await mkdir(path.join(root, "src/generated"), { recursive: true });
const poets = new Map(),
  seen = new Map(),
  poems = [],
  records = [],
  search = new Map();
const report = {
  sourceCount: source.length,
  imported: 0,
  duplicates: 0,
  missingScripts: 0,
  differingLineCounts: 0,
  missingBiographies: true,
  missingPortraits: true,
  missingMoodTags: true,
  fingerprint,
};
for (const [i, row] of source.entries()) {
  if (
    typeof row.author !== "string" ||
    !row.author.trim() ||
    typeof row.title !== "string" ||
    typeof row.type !== "string"
  )
    throw new Error(`Invalid metadata at row ${i + 1}`);
  for (const script of ["hi", "en", "ur"])
    if (
      !Array.isArray(row[script]) ||
      row[script].some((line) => typeof line !== "string")
    )
      throw new Error(`Invalid ${script} verses at row ${i + 1}`);
  const text = Object.fromEntries(
    ["hi", "en", "ur"]
      .filter((s) => row[s].some((l) => l.trim()))
      .map((s) => [s, row[s].join("\n")]),
  );
  if (!Object.keys(text).length) throw new Error(`Empty poem at row ${i + 1}`);
  const identity = JSON.stringify([norm(row.author), text]);
  const id = `p-${hash(identity)}`;
  if (seen.has(id)) {
    if (seen.get(id) !== identity) throw new Error("ID collision");
    report.duplicates++;
    continue;
  }
  seen.set(id, identity);
  const poetId = `a-${hash(norm(row.author))}`;
  if (!poets.has(poetId))
    poets.set(poetId, {
      id: poetId,
      name: row.author.trim(),
      count: 0,
      genres: [],
    });
  const poet = poets.get(poetId);
  poet.count++;
  if (!poet.genres.includes(row.type)) poet.genres.push(row.type);
  const chunk = `${fingerprint}/${Math.floor(poems.length / 64)}.json`;
  const summary = {
    id,
    poetId,
    title: row.title,
    firstLine:
      (text.hi ?? text.en ?? text.ur).split("\n").find((l) => l.trim()) ??
      row.title,
    genre: row.type,
    scripts: Object.keys(text),
    chunk,
  };
  poems.push(summary);
  records.push({ ...summary, text });
  const words = new Set(
    normalizeSearch(
      [row.title, row.author, row.type, ...Object.values(text)].join(" "),
    ).split(" "),
  );
  for (const word of words) {
    if (!word) continue;
    if (!search.has(word)) search.set(word, []);
    search.get(word).push((poems.length - 1).toString(36));
  }
  if (Object.keys(text).length < 3) report.missingScripts++;
  if (new Set(["hi", "en", "ur"].map((s) => row[s].length)).size > 1)
    report.differingLineCounts++;
}
const modules = [];
for (let i = 0; i < records.length; i += 64) {
  const n = Math.floor(i / 64);
  await writeFile(
    path.join(dir, `${n}.json`),
    JSON.stringify(records.slice(i, i + 64)),
  );
  modules.push(
    `  '${fingerprint}/${n}.json': () => require('../../public/data/${fingerprint}/${n}.json'),`,
  );
}
await writeFile(
  path.join(dir, "search.json"),
  JSON.stringify({
    tokens: [...search.keys()],
    postings: [...search.values()].map((ids) => ids.join(".")),
  }),
);
const catalog = {
  version: 1,
  fingerprint,
  poets: [...poets.values()],
  poems,
  genres: [...new Set(poems.map((p) => p.genre))],
  sourceCount: source.length,
};
await writeFile(
  path.join(root, "src/generated/catalog.json"),
  JSON.stringify(catalog),
);
await writeFile(
  path.join(root, "src/generated/chunks.ts"),
  `// Generated by scripts/build-data.mjs. Native lazy module loading.\nimport type { Poem, SearchIndex } from '../data/types';\nexport const chunks: Record<string, () => Poem[]> = {\n${modules.join("\n")}\n};\nexport const loadSearch = (): SearchIndex => require('../../public/data/${fingerprint}/search.json');\n`,
);
report.imported = poems.length;
await writeFile(
  path.join(root, "DATA-AUDIT.json"),
  JSON.stringify(report, null, 2),
);
console.log(
  JSON.stringify(
    { ...report, poets: poets.size, chunks: modules.length },
    null,
    2,
  ),
);
